#!/usr/bin/env python3
"""Generate CODEBOOK.md from the current pattern CSV and check drift."""

from __future__ import annotations

import argparse
import csv
import hashlib
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "literary_and_video_patterns.csv"
OUTPUT = ROOT / "CODEBOOK.md"

REQUIRED_FIELDS = (
    "pattern_id",
    "label_type",
    "label",
    "definition",
    "inclusion_criteria",
    "exclusion_criteria",
    "analysis_unit",
    "literature_indicators",
    "video_indicators",
    "invented_example",
    "related_patterns",
    "original_workbook_mapping",
    "evidence_required",
    "annotation_rule",
    "sequence_recording",
    "creative_use",
    "interpretation_boundary",
    "status",
)


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def load_rows() -> tuple[list[dict[str, str]], str]:
    if not SOURCE.exists():
        fail(f"source CSV not found: {SOURCE}")

    data = SOURCE.read_bytes()
    digest = hashlib.sha256(data).hexdigest()

    with SOURCE.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None:
            fail("source CSV has no header")
        missing = [field for field in REQUIRED_FIELDS if field not in reader.fieldnames]
        if missing:
            fail(f"source CSV is missing required fields: {', '.join(missing)}")
        rows = list(reader)

    if not rows:
        fail("source CSV has no pattern rows")

    ids = [row["pattern_id"].strip() for row in rows]
    if any(not pattern_id for pattern_id in ids):
        fail("source CSV contains an empty pattern_id")
    duplicates = sorted({pattern_id for pattern_id in ids if ids.count(pattern_id) > 1})
    if duplicates:
        fail(f"source CSV contains duplicate pattern IDs: {', '.join(duplicates)}")

    return rows, digest


def render(rows: list[dict[str, str]], digest: str) -> str:
    label_types = sorted({row["label_type"] for row in rows})
    lines = [
        "---",
        "document_id: DOC-201",
        "title: Pattern Codebook",
        "status: proposed",
        "owner: unresolved",
        "created: 2026-11-11",
        "updated: 2026-11-11",
        "applies_to: literary_and_video_patterns.csv",
        "authority: controlled",
        "supersedes: null",
        "related:",
        "  - DOC-001",
        "  - DOC-202",
        "  - DOC-302",
        "---",
        "",
        "# Pattern Codebook",
        "",
        "> Generated file. Edit `literary_and_video_patterns.csv` and run "
        "`python3 scripts/generate_codebook.py`. Do not edit this file by hand.",
        "",
        "## Purpose and status",
        "",
        "This codebook presents the current proposed coding rules for literary and",
        "audiovisual patterns. It is not a validated instrument. The source CSV",
        "contains the working definitions; this file provides a readable view and",
        "makes the evidence and interpretation boundaries visible during review.",
        "",
        "Source: `literary_and_video_patterns.csv`",
        "",
        f"Rows: {len(rows)}",
        "",
        f"Source SHA-256: `{digest}`",
        "",
        "## Coding workflow",
        "",
        "1. Identify the work, edition or version, and analysis unit.",
        "2. Apply one or more pattern definitions only where independently supported.",
        "3. Record `present`, `absent`, `uncertain`, or `not_applicable`.",
        "4. Record a located quotation, description, or timestamp span.",
        "5. State the rationale in terms of the inclusion and exclusion criteria.",
        "6. For sequential patterns, link event IDs in presentation order and record",
        "   story order only where it is recoverable.",
        "7. Retain uncertainty and alternative readings. Do not collapse them into",
        "   a positive label.",
        "8. Treat pattern presence, narrative function, and proposed effect as",
        "   separate coding decisions.",
        "",
        "## Analysis units",
        "",
        "| Unit | Working definition | Segmentation rule |",
        "|---|---|---|",
        "| work | Complete work as published or released | Identify the edition or version; use a single work-level record |",
        "| chapter | Named or numbered division of a literary work | Use the publisher's or author's divisions; do not invent divisions |",
        "| scene | Continuous action in one time and place with stable participants | Break at time jumps, location changes, or wholesale participant turnover |",
        "| passage | Contiguous text selected because it supports a pattern | Record start and end locators; use 1-3 sentences to a paragraph as a starting norm, not a rule |",
        "| sequence | Contiguous audiovisual span with a stable framing, editing, or sound regime | Record start and end timestamps; break at a hard cut to a new time or location when that changes the relevant unit |",
        "",
        "These unit definitions are proposed. They need pilot adjudication before they",
        "can support comparable agreement statistics.",
        "",
        "## Label types in the current source",
        "",
    ]
    for label_type in label_types:
        count = sum(1 for row in rows if row["label_type"] == label_type)
        lines.append(f"- `{label_type}`: {count} pattern{'s' if count != 1 else ''}")

    lines.extend(
        [
            "",
            "## Evidence and sequence defaults",
            "",
            "Every source row currently repeats the same global evidence, annotation,",
            "and sequence rules. They are reproduced once here because per-pattern",
            "overrides have not yet been separated in the source data.",
            "",
            f"**Evidence required:** {rows[0]['evidence_required']}",
            "",
            f"**Annotation rule:** {rows[0]['annotation_rule']}",
            "",
            f"**Sequence recording:** {rows[0]['sequence_recording']}",
            "",
            "Per-pattern evidence overrides described in the design proposal are not",
            "yet authoritative. The strongest sequential patterns need multiple linked",
            "locators, not a single passage tag.",
            "",
            "## Pattern register",
            "",
        ]
    )

    for row in rows:
        lines.extend(
            [
                f"### {row['pattern_id']} - {row['label']}",
                "",
                f"- Label type: `{row['label_type']}`",
                f"- Status: {row['status']}",
                f"- Analysis unit: {row['analysis_unit']}",
                f"- Related patterns in source notation: {row['related_patterns']}",
                f"- Source-workbook mapping: {row['original_workbook_mapping']}",
                "",
                f"**Definition:** {row['definition']}",
                "",
                f"**Inclusion criteria:** {row['inclusion_criteria']}",
                "",
                f"**Exclusion criteria:** {row['exclusion_criteria']}",
                "",
                f"**Literature indicators:** {row['literature_indicators']}",
                "",
                f"**Video indicators:** {row['video_indicators']}",
                "",
                f"**Invented example:** {row['invented_example']}",
                "",
                f"**Creative use:** {row['creative_use']}",
                "",
                f"**Interpretation boundary:** {row['interpretation_boundary']}",
                "",
            ]
        )

    lines.extend(
        [
            "## Review warnings",
            "",
            "- The relation list has no controlled direction or relation type.",
            "- Indicators are stored as comma or semicolon text rather than separate",
            "  observations.",
            "- The examples are invented unless a row states otherwise.",
            "- Cross-media analogues are proposals unless separately tested.",
            "- Status is uniform and therefore carries no comparative evidence.",
            "- The tight sequential and irony clusters require boundary adjudication",
            "  before agreement results are interpretable.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="check whether CODEBOOK.md is current instead of writing it",
    )
    args = parser.parse_args()

    rows, digest = load_rows()
    rendered = render(rows, digest)

    if args.check:
        if not OUTPUT.exists():
            fail(f"generated codebook not found: {OUTPUT}")
        if OUTPUT.read_text(encoding="utf-8") != rendered:
            fail("CODEBOOK.md is stale; run python3 scripts/generate_codebook.py")
        print(f"ok: {len(rows)} patterns; CODEBOOK.md matches {SOURCE.name}")
        return 0

    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} from {len(rows)} patterns")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
