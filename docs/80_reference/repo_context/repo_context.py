class ContextError(ValueError):
    """An input could not be safely or unambiguously processed."""


def clean_relative(value: str) -> str:
    if not isinstance(value, str) or not value or "\\" in value:
        raise ContextError(f"expected a repository-relative POSIX path, got {value!r}")
    parts = value.split("/")
    if any(part in {"", ".", ".."} or ":" in part for part in parts):
        raise ContextError(f"unsafe repository-relative path: {value!r}")
    return PurePosixPath(value).as_posix()


def local_path(root: Path, relative: str) -> Path:
    path = root
    for part in clean_relative(relative).split("/"):
        path = path / part
        if path.is_symlink():
            raise ContextError(f"symlink is outside the context trust boundary: {relative}")
    return path


def read_bytes(path: Path) -> bytes:
    if not stat.S_ISREG(path.stat().st_mode):
        raise ContextError(f"expected a regular file: {path.name}")
    with path.open("rb") as source:
        data = source.read(MAX_TEXT + 1)
    if len(data) > MAX_TEXT:
        raise ContextError(f"text exceeds {MAX_TEXT} bytes: {path.name}")
    return data


def read_json(path: Path) -> dict:
    document = json.loads(read_bytes(path).decode("utf-8"))
    if not isinstance(document, dict):
        raise ContextError(f"expected a JSON object: {path.name}")
    return document


def is_secret(path: Path) -> bool:
    name = path.name.casefold()
    return name in SECRET_NAMES or name.startswith(".env.") or path.suffix.casefold() in SECRET_SUFFIXES


def scan_files(root: Path, context: str, exclusions: list[str]) -> tuple[list[str], list[str]]:
    files: list[str] = []
    nested: list[str] = []

    def excluded(relative: str) -> bool:
        return relative == context or any(fnmatchcase(relative, pattern) for pattern in exclusions)

    def scan_error(error: OSError) -> None:
        raise error

    for parent, dirs, names in os.walk(root, topdown=True, onerror=scan_error, followlinks=False):
        folder = Path(parent)
        keep = []
        for name in sorted(dirs):
            directory = folder / name
            relative = directory.relative_to(root).as_posix()
            if name.casefold() in SKIP_DIRS or excluded(relative) or directory.is_symlink() or is_secret(directory):
                continue
            if any((directory / marker).exists() for marker in (".git", ".hg", ".svn")):
                nested.append(relative)
                continue
            keep.append(name)
        dirs[:] = keep
        for name in sorted(names):
            path = folder / name
            relative = path.relative_to(root).as_posix()
            if (name == ".DS_Store" or name.casefold() in SKIP_DIRS
                    or excluded(relative) or is_secret(path) or path.is_symlink()):
                continue
            if stat.S_ISREG(path.stat().st_mode):
                files.append(relative)
                if len(files) > MAX_FILES:
                    raise ContextError(f"scan exceeds {MAX_FILES} files; narrow scope with an exclusion")
    return sorted(files), sorted(nested)


def config_role(path: PurePosixPath) -> str | None:
    name = path.name
    if path.parts[:2] in {(".github", "workflows"), (".circleci", "config.yml")} and path.suffix in {".yml", ".yaml"}:
        return "CI workflow"
    if name == "plugin.json" and path.parent.name in {".claude-plugin", ".codex-plugin", ".factory-plugin", ".qoder-plugin"}:
        return "Agent plugin manifest"
    if name.startswith("Dockerfile.") or name.startswith("Containerfile."):
        return "Container build"
    if name in LOCKFILES:
        return "Dependency lockfile"
    if name.startswith("requirements") and path.suffix in {".txt", ".in"}:
        return "Python dependencies"
    if path.suffix in {".csproj", ".fsproj", ".vbproj", ".sln", ".slnx"}:
        return ".NET build"
    return CONFIG.get(name)


def requirement_names(values: object) -> list[str]:
    if not isinstance(values, list):
        return []
    return [match[1] for value in values if isinstance(value, str) and (match := REQUIREMENT.match(value))]


def table(parent: dict, key: str) -> dict:
    child = parent.get(key, {})
    return child if isinstance(child, dict) else {}


def inspect_file(path: PurePosixPath, role: str | None, source: str) -> tuple[list, list, list]:
    entries, deps, signals = [], [], []

    def dependency(name: str, scope: str) -> None:
        if PACKAGE.fullmatch(name) and not name.startswith("."):
            deps.append((scope, name))
            if name.casefold() in FRAMEWORKS:
                signals.append(("Declared framework or CLI toolkit", name))

    def entry(kind: str, name: str, target: str = "") -> None:
        if TOKEN.fullmatch(name) and (not target or TOKEN.fullmatch(target)):
            entries.append((kind, name, target))

    def dependency_table(parent: dict, scopes: tuple[str, ...]) -> None:
        for scope in scopes:
            for name in table(parent, scope):
                dependency(name, scope)

    if path.name == "package.json" or path.name == "composer.json":
        config = json.loads(source)
        if not isinstance(config, dict):
            raise ContextError("manifest must be a JSON object")
        dependency_table(config, (
            "dependencies", "devDependencies", "optionalDependencies", "peerDependencies", "require", "require-dev",
        ))
        for name in table(config, "scripts"):
            entry("Declared script", name)
        if config.get("workspaces"):
            signals.append(("Workspace declaration", "package workspaces"))
        binaries = config.get("bin")
        if isinstance(binaries, str) and isinstance(config.get("name"), str):
            entry("Declared binary", config["name"], binaries)
        elif isinstance(binaries, dict):
            for name, target in binaries.items():
                if isinstance(target, str):
                    entry("Declared binary", name, target)
        for key in ("main", "module"):
            if isinstance(config.get(key), str):
                entry("Declared library target", key, config[key])
        if isinstance(config.get("exports"), str):
            entry("Declared library target", "exports", config["exports"])
        elif config.get("exports"):
            signals.append(("Library export configuration", "exports"))

    elif path.name in {"pyproject.toml", "Cargo.toml", "Pipfile"}:
        config = tomllib.loads(source)
        if path.name == "pyproject.toml":
            project = table(config, "project")
            for name in requirement_names(project.get("dependencies")):
                dependency(name, "dependencies")
            for group, values in table(project, "optional-dependencies").items():
                for name in requirement_names(values):
                    dependency(name, f"optional:{group}")
            for group, values in table(config, "dependency-groups").items():
                for name in requirement_names(values):
                    dependency(name, f"group:{group}")
            for name in requirement_names(table(config, "build-system").get("requires")):
                dependency(name, "build-system")
            poetry = table(table(config, "tool"), "poetry")
            dependency_table(poetry, ("dependencies", "dev-dependencies"))
            for group, values in table(poetry, "group").items():
                if isinstance(values, dict):
                    for name in table(values, "dependencies"):
                        dependency(name, f"poetry:{group}")
            for scripts in (table(project, "scripts"), table(project, "gui-scripts"), table(poetry, "scripts")):
                for name, target in scripts.items():
                    if isinstance(target, str):
                        entry("Declared Python command", name, target)
        elif path.name == "Cargo.toml":
            scopes = ("dependencies", "dev-dependencies", "build-dependencies")
            dependency_table(config, scopes)
            if "workspace" in config:
                signals.append(("Workspace declaration", "Cargo workspace"))
                dependency_table(table(config, "workspace"), scopes)
            for values in table(config, "target").values():
                if isinstance(values, dict):
                    dependency_table(values, scopes)
            for binary in list_value(config.get("bin", []), "Cargo bin"):
                if isinstance(binary, dict) and isinstance(binary.get("name"), str):
                    target = binary.get("path", "")
                    if isinstance(target, str):
                        entry("Declared Rust binary", binary["name"], target)
        else:
            dependency_table(config, ("packages", "dev-packages"))

    elif role == "Python dependencies":
        for name in requirement_names(source.splitlines()):
            dependency(name, "requirements declaration")

    elif path.name == "go.mod":
        block = False
        for line in source.splitlines():
            line = line.split("//", 1)[0].strip()
            if line.startswith("require") and line.split()[0] == "require":
                line = line.removeprefix("require").strip()
                if line == "(":
                    block = True
                    continue
            elif line == ")":
                block = False
                continue
            elif not block:
                continue
            fields = line.split()
            if len(fields) == 2:
                dependency(fields[0], "require")

    elif path.name == "pom.xml" or path.suffix in {".csproj", ".fsproj", ".vbproj"}:
        if re.search(r"<!\s*(?:DOCTYPE|ENTITY)", source, re.I):
            raise ContextError("XML declarations with entities or DTDs are unsupported")
        document = ET.fromstring(source)
        for item in document.iter():
            tag = item.tag.rsplit("}", 1)[-1]
            if tag == "dependency":
                children = {child.tag.rsplit("}", 1)[-1]: (child.text or "").strip() for child in item}
                group, artifact = children.get("groupId", ""), children.get("artifactId", "")
                if PACKAGE.fullmatch(group) and PACKAGE.fullmatch(artifact):
                    name = f"{group}:{artifact}"
                    deps.append(("Maven dependency", name))
                    if name.casefold() in FRAMEWORKS:
                        signals.append(("Declared framework or CLI toolkit", name))
            elif tag == "PackageReference" and (package := item.get("Include")):
                dependency(package, "NuGet PackageReference")
            elif tag == "modules" and len(item):
                signals.append(("Module declaration", "Maven modules"))

    elif role == "CI workflow":
        for name in ACTION.findall(source):
            if not name.startswith("."):
                dependency(name, "workflow action")

    elif role == "Container build":
        for image in FROM.findall(source):
            if TOKEN.fullmatch(image) and not image.startswith("-"):
                deps.append(("FROM target (image or stage)", image))

    elif path.suffix == ".py":
        if path.name == "__main__.py":
            entry("Python package launch file", path.name)
        if "__main__" in source:
            module = ast.parse(source)
            for node in module.body:
                if not isinstance(node, ast.If) or not isinstance(node.test, ast.Compare):
                    continue
                test = node.test
                if len(test.ops) == 1 and isinstance(test.ops[0], ast.Eq):
                    pair = (test.left, test.comparators[0])
                    if (any(isinstance(item, ast.Name) and item.id == "__name__" for item in pair)
                            and any(isinstance(item, ast.Constant) and item.value == "__main__" for item in pair)):
                        entry("Python main guard", path.name)
                        break

    elif path.suffix == ".go" and re.search(r"(?m)^package\s+main\b", source):
        if re.search(r"(?m)^func\s+main\s*\(", source):
            entry("Go main marker", path.name)
    elif path.suffix == ".rs" and re.search(r"(?m)^\s*(?:async\s+)?fn\s+main\s*\(", source):
        entry("Rust main marker", path.name)

    if path.name in {"pnpm-workspace.yaml", "go.work"}:
        signals.append(("Workspace declaration", path.name))
    if path.name == "SKILL.md" and source.startswith("---"):
        entry("Agent skill entry document", path.name)
    return sorted(set(entries)), sorted(set(deps)), sorted(set(signals))


def inventory(root: Path, files: list[str], nested: list[str]) -> dict:
    counts: Counter[str] = Counter()
    layout: dict[str, dict] = {}
    configs, entries, deps, signals, warnings = [], [], [], [], []
    for relative in files:
        path = PurePosixPath(relative)
        language = LANGUAGES.get(path.suffix.casefold())
        if language:
            counts[language] += 1
        for depth in range(1, min(len(path.parts) - 1, MAP_DEPTH) + 1):
            directory = PurePosixPath(*path.parts[:depth]).as_posix()
            summary = layout.setdefault(directory, {"files": 0, "languages": Counter()})
            summary["files"] += 1
            if language:
                summary["languages"][language] += 1
        role = config_role(path)
        if role:
            configs.append((relative, role))
        if role is None and path.suffix not in {".py", ".go", ".rs"} and path.name != "SKILL.md":
            continue
        if role == "Dependency lockfile":
            continue
        try:
            source = read_bytes(root / relative).decode("utf-8-sig")
            file_entries, file_deps, file_signals = inspect_file(path, role, source)
        except (ValueError, SyntaxError, ET.ParseError, OSError) as error:
            # Parser diagnostics can contain raw source or credentials.
            warnings.append((relative, type(error).__name__))
            continue
        entries.extend((relative, *row) for row in file_entries)
        deps.extend((relative, *row) for row in file_deps)
        signals.extend((relative, *row) for row in file_signals)
    return {
        "file_count": len(files),
        "path_sha256": hashlib.sha256("\0".join(files).encode("utf-8", errors="surrogateescape")).hexdigest(),
        "root_files": [relative for relative in files if "/" not in relative],
        "directories": layout,
        "nested_repositories": nested,
        "languages": counts,
        "configurations": configs,
        "entrypoint_candidates": entries,
        "dependency_declarations": deps,
        "stack_signals": signals,
        "unread_or_unparsed": warnings,
    }


def list_value(value: object, label: str) -> list:
    if not isinstance(value, list):
        raise ContextError(f"{label} must be a list")
    return value


def nonempty(value: object, label: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ContextError(f"{label} must be non-empty text")
    return value


def excludes(value: object) -> list[str]:
    return [clean_relative(item) for item in list_value(value, "exclude")]


def code(value: str) -> str:
    value = value.replace("\n", r"\n").replace("\r", r"\r")
    length = max((len(item) for item in re.findall(r"\x60+", value)), default=0) + 1
    marker = chr(96) * length
    return f"{marker} {value} {marker}" if chr(96) in value else f"{marker}{value}{marker}"


def link(path: str, context: str, line: int | None = None) -> str:
    relative = os.path.relpath(path, context).replace(os.sep, "/")
    fragment = f"#L{line}" if line is not None else ""
    suffix = f":{line}" if line is not None else ""
    return f"[{code(path + suffix)}]({quote(relative)}{fragment})"


class Evidence:
    def __init__(self, root: Path, context: str, files: list[str]):
        self.root = root
        self.context = context
        self.files = set(files)
        self.hashes: dict[str, str] = {}
        self.sources: dict[str, str] = {}

    def citation(self, source: object) -> str:
        if not isinstance(source, dict) or source.keys() != {"path", "anchor"}:
            raise ContextError("each source must have exactly path and anchor")
        path = clean_relative(source["path"])
        anchor = nonempty(source["anchor"], f"anchor for {path}").replace("\r\n", "\n")
        if path not in self.files:
            raise ContextError(f"evidence source is missing or outside the scan scope: {path}")
        if path not in self.sources:
            data = read_bytes(local_path(self.root, path))
            text = data.decode("utf-8-sig").replace("\r\n", "\n")
            self.sources[path] = text
            self.hashes[path] = hashlib.sha256(text.encode("utf-8")).hexdigest()
        contents = self.sources[path]
        index = contents.find(anchor)
        if index < 0:
            raise ContextError(f"evidence anchor not found: {path}")
        if contents.find(anchor, index + 1) >= 0:
            raise ContextError(f"evidence anchor is ambiguous: {path}")
        return link(path, self.context, contents.count("\n", 0, index) + 1)

    def claim(self, claim: object) -> str:
        if not isinstance(claim, dict) or claim.keys() - {"name", "text", "sources"}:
            raise ContextError("claim must contain text and sources, with an optional name")
        text = nonempty(claim.get("text"), "claim text").strip()
        sources = list_value(claim.get("sources"), "claim sources")
        if not sources:
            raise ContextError("every claim requires evidence")
        heading = f"**{nonempty(claim['name'], 'claim name')}**. " if "name" in claim else ""
        return f"{heading}{text} ({', '.join(self.citation(source) for source in sources)})"

    def claims(self, document: dict, name: str, *, required: bool = False) -> list[str]:
        entries = list_value(document.get(name, []), name)
        if required and not entries:
            raise ContextError(f"{name} needs at least one reviewed claim")
        return [self.claim(entry) for entry in entries]


def listing(items: list[str], absent: str, *, ordered: bool = False) -> str:
    if not items:
        return absent
    return "\n".join(f"{f'{i}.' if ordered else '-'} {item}" for i, item in enumerate(items, 1))


def map_page(data: dict, context: str, reviewed: list[str]) -> str:
    lines = ["# Repository map", "", "## Reviewed entrypoints", "",
             listing(reviewed, "No reviewed entrypoints recorded."), "", "## Directory inventory", ""]
    if data["languages"]:
        lines.extend(("Files by extension: " + ", ".join(
            f"{name} ({count})" for name, count in sorted(data["languages"].items())
        ) + ".", ""))
    lines.append(f"Indexed {data['file_count']} files. Directory display depth is {MAP_DEPTH}.")
    if data["directories"]:
        lines.append("")
        for path, summary in sorted(data["directories"].items()):
            indent = "  " * path.count("/")
            lines.append(f"{indent}- {link(path, context)} ({summary['files']} files in subtree)")
    if data["root_files"]:
        lines.extend(("", "Root files: " + ", ".join(link(path, context) for path in data["root_files"]) + "."))
    if data["nested_repositories"]:
        lines.extend(("", "Separate repositories skipped: " + ", ".join(
            link(path, context) for path in data["nested_repositories"]
        ) + "."))
    for title, key in (
        ("Build, configuration, and CI", "configurations"),
        ("Static launch candidates", "entrypoint_candidates"),
        ("Stack signals", "stack_signals"),
        ("Files the scanner could not analyse", "unread_or_unparsed"),
    ):
        rows = data[key]
        if rows:
            lines.extend(("", f"## {title}", "", *(
                f"- {link(path, context)}: {' · '.join(code(item) for item in fields if item)}"
                for path, *fields in rows
            )))
    return "\n".join(lines)


def render(root: Path, context: str, document: dict, files: list[str], data: dict) -> dict[str, bytes]:
    if type(document.get("schema")) is not int or document["schema"] != SCHEMA:
        raise ContextError(f"evidence.json must declare schema {SCHEMA}")
    if unknown := document.keys() - {"schema", "exclude", "identity", "entrypoints", "modules", "flows", "dependencies", "onboarding"}:
        raise ContextError(f"unknown evidence keys: {', '.join(sorted(unknown))}")
    evidence = Evidence(root, context, files)
    identity = evidence.claims(document, "identity", required=True)
    onboarding = evidence.claims(document, "onboarding", required=True)
    reviewed_entries = evidence.claims(document, "entrypoints")
    modules = evidence.claims(document, "modules")
    dependencies = evidence.claims(document, "dependencies")
    flows = []
    for flow in list_value(document.get("flows", []), "flows"):
        if not isinstance(flow, dict) or flow.keys() != {"name", "steps"}:
            raise ContextError("each flow must have exactly name and steps")
        name = nonempty(flow["name"], "flow name")
        steps = list_value(flow["steps"], f"steps for {name}")
        if not steps:
            raise ContextError(f"flow needs at least one step: {name}")
        flows.append(f"## {name}\n\n{listing([evidence.claim(step) for step in steps], '', ordered=True)}")

    commands = f"python3 {shlex.quote(context + '/repo_context.py')}"
    refresh = f"{commands} --refresh --root . --context {shlex.quote(context)}"
    check = f"{commands} check --root . --context {shlex.quote(context)}"
    dependency_rows: dict[tuple[str, str], list[str]] = defaultdict(list)
    for path, scope, name in data["dependency_declarations"]:
        dependency_rows[(path, scope)].append(code(name))
    docs = {
        "README.md": (
            "# Agent onboarding\n\n" + listing(identity, "") +
            "\n\n## Read and verify in this order\n\n" + listing(onboarding, "", ordered=True) +
            "\n\n## Context pack\n\n"
            "- [Repository map and entrypoints](map.md)\n"
            "- [Architecture and module boundaries](architecture.md)\n"
            "- [Critical flows](flows.md)\n"
            "- [External dependencies](dependencies.md)\n"
            "\n## Maintenance\n\nRun these commands from the repository root.\n\n"
            f"- Refresh with {code(refresh)}\n- Check with {code(check)}\n"
            "- Reviewed inputs are in [evidence.json](evidence.json).\n\n"
            "Refresh reuses the reviewed inputs. If cited sources change, review them and update "
            "`evidence.json` as needed before adding `--reviewed` to the refresh command."
        ),
        "map.md": map_page(data, context, reviewed_entries),
        "architecture.md": "# Architecture and module boundaries\n\n" +
            listing(modules, "No reviewed module boundaries recorded."),
        "flows.md": "# Critical flows\n\n" + ("\n\n".join(flows) or "No reviewed flows recorded."),
        "dependencies.md": (
            "# External dependencies\n\n## Reviewed usage\n\n" +
            listing(dependencies, "No reviewed dependency usage recorded.") +
            "\n\n## Static declarations\n\n" +
            listing([f"{link(path, context)} ({scope}): {', '.join(names)}"
                     for (path, scope), names in sorted(dependency_rows.items())],
                    "The supported static scanners detected no dependency declarations.")
        ),
    }
    result = {name: f"{MARKER}\n\n{text}\n".encode("utf-8") for name, text in docs.items()}
    snapshot = {"generated_by": "repo_context", "schema": SCHEMA, "inventory": data,
                "evidence_source_sha256": evidence.hashes}
    result["snapshot.json"] = (json.dumps(snapshot, ensure_ascii=True, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return result


def owned_bytes(path: Path) -> bytes | None:
    if not path.exists():
        return None
    if not stat.S_ISREG(path.stat().st_mode):
        raise ContextError(f"output is not a regular file: {path.name}")
    with path.open("rb") as stream:
        current = stream.read().replace(b"\r\n", b"\n")
    if path.name == "snapshot.json":
        document = json.loads(current)
        if isinstance(document, dict) and document.get("generated_by") == "repo_context" and document.get("schema") == SCHEMA:
            return current
    elif current.startswith((MARKER + "\n").encode("utf-8")):
        return current
    raise ContextError(f"refusing to replace an unmanaged file: {path.name}")


def replace_file(path: Path, content: bytes) -> None:
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".repo_context-", delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(content)
            stream.close()
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def run(args: argparse.Namespace) -> int:
    root = Path(args.root).resolve(strict=True)
    if not root.is_dir():
        raise ContextError("--root must name a directory")
    context = clean_relative(args.context)
    folder = local_path(root, context)
    if folder.exists() and not folder.is_dir():
        raise ContextError("--context must name a directory inside the repository")
    evidence_path = local_path(root, f"{context}/evidence.json")
    if args.command == "inventory":
        config = read_json(evidence_path) if evidence_path.exists() else {}
        exclusion_rules = excludes(config.get("exclude", [])) + excludes(args.exclude)
    else:
        config = read_json(evidence_path)
        exclusion_rules = excludes(config.get("exclude", []))
    files, nested = scan_files(root, context, exclusion_rules)
    data = inventory(root, files, nested)
    if args.command == "inventory":
        print(json.dumps(data, ensure_ascii=True, indent=2, sort_keys=True))
        return 0

    outputs = render(root, context, config, files, data)
    paths = {name: local_path(root, f"{context}/{name}") for name in outputs}
    current = {name: owned_bytes(path) for name, path in paths.items()}
    stale = [name for name, content in outputs.items() if current[name] != content]
    reviewed_changes = []
    if old_snapshot := current["snapshot.json"]:
        previous = json.loads(old_snapshot)["evidence_source_sha256"]
        now = json.loads(outputs["snapshot.json"])["evidence_source_sha256"]
        reviewed_changes = sorted(path for path in previous.keys() & now.keys() if previous[path] != now[path])
    if reviewed_changes:
        print("Cited sources changed: " + ", ".join(reviewed_changes), file=sys.stderr)
    if args.command == "check":
        if stale:
            print("Stale or missing: " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"Current: {context}")
        return 0
    if reviewed_changes and not args.reviewed:
        print("Review changed sources, revise the evidence as needed, then rerun with --reviewed.", file=sys.stderr)
        return 1
    for name in stale:
        replace_file(paths[name], outputs[name])
    print(f"Refreshed {len(stale)} files in {context}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("command", choices=("inventory", "refresh", "check"), nargs="?")
    mode.add_argument("--refresh", action="store_true", help="refresh the existing pack from saved evidence")
    parser.add_argument("--root", default=".", help="checkout directory (default: current directory)")
    parser.add_argument("--context", default=DEFAULT_CONTEXT, help=f"repo-relative pack directory (default: {DEFAULT_CONTEXT})")
    parser.add_argument("--exclude", default=[], action="append", help="extra repo-relative glob for inventory; repeatable")
    parser.add_argument("--reviewed", action="store_true", help="refresh after re-inspecting changed cited files")
    args = parser.parse_args()
    if args.refresh:
        args.command = "refresh"
    if args.exclude and args.command != "inventory":
        parser.error("store persistent exclusions in evidence.json for refresh/check")
    if args.reviewed and args.command != "refresh":
        parser.error("--reviewed applies only to refresh")
    try:
        return run(args)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"repo_context: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
